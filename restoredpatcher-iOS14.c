static void parse(void) {
    if (length<32 || rd32(0)!=0xfeedfacf || rd32(4)!=0x0100000c || rd32(12)!=2)
        fail("expected thin little-endian ARM64 Mach-O executable");
    size_t end=32+(uint64_t)rd32(20),p=32;
    if (end>length) fail("load commands exceed input");
    unsigned uuid=0,text=0;
    for (uint32_t i=0;i<rd32(16);i++) {
        if (p>end || end-p<8) fail("truncated load command");
        uint32_t c=rd32(p),n=rd32(p+4);
        if (n<8 || n>end-p) fail("invalid load command size");
        if (c==27) {
            if (n!=24 || uuid++ || memcmp(data+p+8,expected_uuid,16))
                fail("unsupported build UUID; expected supplied 14.0 beta 2 restored_external");
        } else if (c==25) {
            if (n<72) fail("truncated segment");
            uint64_t f=rd64(p+40),s=rd64(p+48);
            if (f>length || s>length-f || rd32(p+64)>(n-72)/80) fail("invalid segment bounds");
            for (uint32_t j=0;j<rd32(p+64);j++) {
                size_t q=p+72+j*80;
                if (memcmp(data+q,"__text\0",7) || memcmp(data+q+16,"__TEXT\0",7)) continue;
                if (text++ || !(rd32(p+60)&4)) fail("duplicate or non-executable text section");
                uint64_t v=rd64(q+32),z=rd64(q+40),o=rd32(q+48);
                if (o>length || z>length-o || o<f || o-f>s || z>s-(o-f) ||
                    v<rd64(p+24) || v-rd64(p+24)!=o-f || v-o!=0x100000000ULL)
                    fail("unsupported text mapping");
                for (size_t k=0;k<sizeof(patches)/sizeof(patches[0]);k++)
                    if (patches[k].offset<o || patches[k].offset-o>z || patches[k].size>z-(patches[k].offset-o))
                        fail("target function outside executable text");
                if (o>0x137bc || z<0x14fbc+sizeof(seal_caller)-o) fail("callers outside text");
            }
        } else if (c==0x2c) {
            if (n<24 || rd32(p+16)) fail("encrypted executable unsupported");
        }
        p+=n;
    }
    if (p!=end || uuid!=1 || text!=1) fail("required Mach-O metadata missing");
    if (!span(0x137bc,sizeof(install_caller)) || !span(0x14fbc,sizeof(seal_caller)) ||
        memcmp(data+0x137bc,install_caller,sizeof(install_caller)) ||
        memcmp(data+0x14fbc,seal_caller,sizeof(seal_caller))) fail("restore-stage caller guards differ");
}
static void save(const char *path,mode_t mode) {
    size_t n=strlen(path);if (n>SIZE_MAX-16) fail("output path too long");
    char *tmp=malloc(n+16);if (!tmp) fail("out of memory");
    snprintf(tmp,n+16,"%s.tmp.XXXXXX",path);
    int fd=mkstemp(tmp);if (fd<0) { perror(path);free(tmp);exit(1); }
    if (fchmod(fd,mode&0777)) { close(fd);unlink(tmp);free(tmp);fail("cannot set output mode"); }
    FILE *f=fdopen(fd,"wb");
    if (!f) { close(fd);unlink(tmp);free(tmp);fail("cannot open output stream"); }
    int bad=fwrite(data,1,length,f)!=length;
    if (fclose(f)) bad=1;
    if (bad) { unlink(tmp);free(tmp);fail("cannot write complete output"); }
    if (rename(tmp,path)) { perror(path);unlink(tmp);free(tmp);exit(1); }
    free(tmp);
}
int main(int argc,char **argv) {
    if (argc!=3) { fprintf(stderr,"Usage: %s [input restored] [output restored]\n",argv[0]);return 2; }
    struct stat st,ot;
    if (stat(argv[1],&st)) { perror(argv[1]);return 1; }
    if (!S_ISREG(st.st_mode)) fail("input must be a regular file");
    if (!stat(argv[2],&ot) && st.st_dev==ot.st_dev && st.st_ino==ot.st_ino) fail("output must not alias input");
    FILE *f=fopen(argv[1],"rb");if (!f) { perror(argv[1]);return 1; }
    if (fseek(f,0,SEEK_END)) fail("cannot seek input");
    long size=ftell(f);if (size<32 || fseek(f,0,SEEK_SET)) fail("invalid input size");
    length=(size_t)size;data=malloc(length);if (!data) fail("out of memory");
    if (fread(data,1,length,f)!=length) fail("cannot read complete input");
    if (fclose(f)) fail("input close failed");
    parse();
    /* Validate BOTH complete functions before changing any bytes. */
    unsigned changed=0;
    for (size_t i=0;i<sizeof(patches)/sizeof(patches[0]);i++) {
        struct patch *p=&patches[i];
        if (!span(p->offset,p->size)) fail("truncated target function");
        if (!memcmp(data+p->offset,p->original,p->size)) { p->changed=1;changed++; }
        else if (memcmp(data+p->offset,success,sizeof(success)) ||
                 memcmp(data+p->offset+sizeof(success),p->original+sizeof(success),p->size-sizeof(success)))
            fail("target function differs from original and recognized patched forms; no output written");
    }
    for (size_t i=0;i<sizeof(patches)/sizeof(patches[0]);i++) {
        struct patch *p=&patches[i];memcpy(data+p->offset,success,sizeof(success));
        printf("%s: %s (file 0x%zx)\n",p->name,p->changed?"patched to return success":"already patched",p->offset);
    }
    save(argv[2],st.st_mode);
    printf("Wrote %s (%zu bytes, unchanged size).\n",argv[2],length);
    if (changed) puts("Code signature is stale; re-sign with the original entitlements before installation.");
    puts("SSV root-hash requests and system-volume sealing are bypassed; device restore/boot still requires testing.");
    free(data);return 0;
}
